#!/usr/bin/env node

/**
 * Generate Version Info
 *
 * Writes `src/version.ts` — what `nuramaClient.getVersion()` reports. It never
 * writes `package.json`.
 *
 * External releases are numbered by the release workflow
 * (`.github/workflows/release-sdk.yml`), which passes the number in as
 * `SDK_RELEASE_VERSION`; see `release-version.cjs` for how it is chosen. Every
 * other build — local, dev watch, staging/production web — reports
 * `<package.json version>+<source hash>`, so it is never mistaken for a release
 * and identical source gives an identical string on any machine.
 *
 * This used to bump the patch version on every local build whose source had
 * changed, counting from a gitignored per-machine file, so two developers
 * produced the same number for different code and a stale working copy could
 * rewrite the committed version downwards.
 *
 * `version.ts` is only rewritten when the version or source hash changes, so the
 * dev watcher (`scripts/dev.cjs`) can call this on every save without making tsc
 * recompile in a loop.
 */

const fs = require('fs');
const path = require('path');
const { createHash } = require('crypto');
const { execSync } = require('child_process');

const ROOT_DIR = path.join(__dirname, '..');
const SRC_DIR = path.join(ROOT_DIR, 'src');
const TYPES_DIR = path.join(ROOT_DIR, '..', 'types');
const VERSION_FILE = path.join(SRC_DIR, 'version.ts');
const PACKAGE_JSON = path.join(ROOT_DIR, 'package.json');

/** Source files under a directory, sorted, excluding the generated version.ts. */
function listSourceFiles(dirPath, files = []) {
  for (const entry of fs.readdirSync(dirPath, { withFileTypes: true })) {
    const filePath = path.join(dirPath, entry.name);
    if (entry.isDirectory()) {
      listSourceFiles(filePath, files);
    } else if (/\.(ts|js)$/.test(entry.name) && filePath !== VERSION_FILE) {
      files.push(filePath);
    }
  }
  return files.sort();
}

/** MD5 of the given directories' source files, paths included so renames count. */
function hashSources(dirs, extra = []) {
  const hash = createHash('md5');
  for (const dir of dirs) {
    if (!fs.existsSync(dir)) continue;
    for (const file of listSourceFiles(dir)) {
      hash.update(path.relative(ROOT_DIR, file));
      hash.update(fs.readFileSync(file));
    }
  }
  for (const value of extra) hash.update(value);
  return hash.digest('hex');
}

/** Hash of the SDK's own source — what `getVersion().buildHash` reports. */
const sourceHash = () => hashSources([SRC_DIR]);

/** The runtime dependency ranges a package publishes with. */
const dependencyRanges = (packageDir) => {
  const pkg = JSON.parse(fs.readFileSync(path.join(packageDir, 'package.json'), 'utf8'));
  return JSON.stringify([pkg.dependencies || {}, pkg.peerDependencies || {}]);
};

/**
 * Hash of everything a release ships: SDK and types source plus their
 * dependency ranges. The release workflow publishes a new version only when
 * this differs from the last release's.
 */
const releaseHash = () => hashSources(
  [SRC_DIR, path.join(TYPES_DIR, 'src')],
  [dependencyRanges(ROOT_DIR), dependencyRanges(TYPES_DIR)],
);

function git(args) {
  try {
    return execSync(`git ${args}`, { cwd: ROOT_DIR, stdio: ['ignore', 'pipe', 'ignore'] }).toString().trim();
  } catch {
    return '';
  }
}

const packageVersion = () => JSON.parse(fs.readFileSync(PACKAGE_JSON, 'utf8')).version;

function versionInfo() {
  const buildHash = sourceHash();
  const base = packageVersion();
  return {
    version: process.env.SDK_RELEASE_VERSION || `${base}+${buildHash.slice(0, 8)}`,
    buildTimestamp: new Date().toISOString(),
    buildHash,
    gitCommit: git('rev-parse --short HEAD') || 'unknown',
    // Uncommitted SDK source changes: the commit alone doesn't describe this build.
    dirty: git('status --porcelain -- src') !== '',
  };
}

/** Write version.ts, unless it already describes this version and source. Returns whether it wrote. */
function writeVersionFile() {
  const info = versionInfo();
  if (fs.existsSync(VERSION_FILE)) {
    const current = fs.readFileSync(VERSION_FILE, 'utf8');
    if (
      current.includes(`version: '${info.version}'`)
      && current.includes(`buildHash: '${info.buildHash}'`)
      && current.includes(`gitCommit: '${info.gitCommit}'`)
      && current.includes(`dirty: ${info.dirty}`)
    ) {
      return false;
    }
  }

  fs.writeFileSync(
    VERSION_FILE,
    `/**
 * SDK Version Information
 * AUTO-GENERATED by scripts/generate-version-info.cjs - DO NOT EDIT MANUALLY
 */

export interface SDKVersionInfo {
  /** The release number for a published build; \`<package.json version>+<source hash>\` for any other build. */
  version: string;
  buildTimestamp: string;
  buildHash: string;
  gitCommit: string;
  /** The build included uncommitted SDK changes. */
  dirty: boolean;
}

export const SDK_VERSION: SDKVersionInfo = {
  version: '${info.version}',
  buildTimestamp: '${info.buildTimestamp}',
  buildHash: '${info.buildHash}',
  gitCommit: '${info.gitCommit}',
  dirty: ${info.dirty},
};
`,
  );
  console.log(`[Version Gen] ${info.version} (${info.gitCommit}${info.dirty ? ', dirty' : ''})`);
  return true;
}

module.exports = { writeVersionFile, sourceHash, releaseHash, packageVersion };

if (require.main === module) {
  const [command] = process.argv.slice(2);
  if (command === '--release-hash') {
    console.log(releaseHash());
  } else {
    writeVersionFile();
  }
}
